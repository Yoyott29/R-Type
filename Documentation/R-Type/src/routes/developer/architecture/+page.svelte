<h2 class="mt-9 text-lg font-semibold">A match, from start to end</h2>

<ol class="mt-3 max-w-[100ch] list-decimal space-y-1.5 pl-6 leading-7">
	<li>In the lobby, each connected player has a ship (the Network plugin creates it from the <code>PlayerPrefabs</code> setting). The first player in is the host.</li>
	<li>The START button adds a <code>StartRequest</code>; while it exists, the client's <code>LobbyMenuScript</code> sets action bit 4 in its input.</li>
	<li>On the server, <code>LobbyServerScript</code> sees that bit in the host's <code>RemoteInput</code>: it sets <code>MatchState.started</code>, refuses new players, clears what is left of the previous match and creates the <code>StageMusic</code> entity.</li>
	<li>The clients see <code>StageMusic</code> arrive: that is how they know a match runs (the lobby hides, the music plays).</li>
	<li>The spawners and the scripts play the match. A killed ship is moved off screen on layer 0.</li>
	<li><code>GameOverScript</code> sees that no ship is alive: it removes the enemies and every replicated entity but the ships, resets the score, accepts players again and clears <code>MatchState.started</code>. The clients see the music go and show the lobby.</li>
</ol>

