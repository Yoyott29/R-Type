<h1 class="text-3xl font-semibold">Architecture</h1>
<p class="mt-1 mb-8 text-[15px] text-[#7f9189]">How R-Type is built on the Gringo Engine: the scene, the scripts, the client and the server</p>

<p class="mt-3 max-w-[100ch] leading-7">
	R-Type is a Gringo project: a scene file, gameplay scripts and assets, turned into two programs by the engine. The server (<code>r-type_server</code>) runs the whole game and is the only authority; the client (<code>r-type_client</code>) sends the keys of its player and shows what the server sends. The engine itself is described in the <a href="/gringo/developer/architecture" class="text-accent hover:underline">Gringo developer documentation</a>: R-Type adds no engine code.
</p>

