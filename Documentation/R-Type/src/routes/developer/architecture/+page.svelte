<h2 class="mt-9 text-lg font-semibold">What goes over the network</h2>

<ul class="mt-3 max-w-[100ch] list-disc space-y-1.5 pl-6 leading-7">
	<li>Client to server: the input bits (directions, charge, start), once per tick.</li>
	<li>Server to clients: every replicated entity with its prefab name and its <code>Transform</code>, 30 times per second, its removal, and the team score. The client creates a copy of the prefab, so sprites and animations are never sent.</li>
</ul>

<p class="mt-3 max-w-[100ch] leading-7">
	The protocol is described in <a href="/gringo/developer/network-protocol" class="text-accent hover:underline">How the protocol works</a>.
</p>

<h2 class="mt-9 text-lg font-semibold">Known couplings</h2>

<ul class="mt-3 max-w-[100ch] list-disc space-y-1.5 pl-6 leading-7">
	<li>Several scripts use the screen size (1920 by 1080) as constants.</li>
	<li>The team score is a <code>GameScore</code> resource of the Network plugin, sent by its own message: a game notion inside the engine.</li>
	<li>The match state is guessed by the clients from the presence of the <code>StageMusic</code> entity.</li>
</ul>
