<h1 class="text-3xl font-semibold">About</h1>
<p class="mt-1 mb-8 text-[15px] text-[#7f9189]">The game and the team behind it</p>

<p class="max-w-[100ch] leading-7">
	TrackNTrap is a 3D multiplayer race between rats. Up to four players run laps around a kitchen
	track full of knives, spatulas and brooms, grab cheese to speed up, and throw mouse traps at each
	other. The first rat to finish 3 laps wins.
</p>

<h2 class="mt-9 text-lg font-semibold">Why a second game</h2>
<p class="mt-3 max-w-[100ch] leading-7">
	TrackNTrap is made with the
	<a href="/gringo/getting-started" class="text-accent hover:underline">Gringo Engine</a>, the same
	engine as R-Type, to show that the engine is not tied to R-Type. The two games share nothing but
	the engine: R-Type is a 2D shoot 'em up, TrackNTrap a 3D race with physics, animated models,
	particles and sound. Both are networked, with an authoritative server and one client per player.
</p>

