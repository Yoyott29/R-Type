<h1 class="text-3xl font-semibold">Architecture</h1>
<p class="mt-1 mb-8 text-[15px] text-[#7f9189]">How TrackNTrap is put together on top of the engine</p>

<p class="mt-3 max-w-[100ch] leading-7">
	TrackNTrap is a Gringo project: a <code>.gringo</code> file describing the scene, a <code>scripts/</code> folder with the gameplay code and an <code>assets/</code> folder. It contains no engine code: physics, rendering, audio, UI and networking all come from the engine plugins.
</p>

<h2 class="mt-9 text-lg font-semibold">Files</h2>

<pre
	class="mt-3 overflow-x-auto rounded-md border border-[#1e2b26] bg-[#121a17] p-4 font-mono text-[13.5px] leading-6"><code>{code0}</code></pre>

<p class="mt-3 max-w-[100ch] leading-7">
	Every script is a header-only C++ class. The editor writes <code>client_main.cpp</code> and <code>server_main.cpp</code> from the <code>.gringo</code> file: they include every script used by an entity or a prefab and create it with its parameters. After changing the scene or adding a script, build again:
</p>

<pre
	class="mt-3 overflow-x-auto rounded-md border border-[#1e2b26] bg-[#121a17] p-4 font-mono text-[13.5px] leading-6"><code>{code1}</code></pre>

<p class="mt-3 max-w-[100ch] leading-7">
	The two generated mains are tracked in git: commit them with your change.
</p>

<h2 class="mt-9 text-lg font-semibold">Plugins</h2>

<p class="mt-3 max-w-[100ch] leading-7">
	<code>2D</code>, <code>UI</code>, <code>3D</code>, <code>Physics3D</code>, <code>Scripts</code>, <code>InputHandler</code>, <code>Audio</code> and <code>Network</code>. Because Network is on, the project is built twice: a headless server (no window, so the plugins that draw are left out) and a client.
</p>

<h2 class="mt-9 text-lg font-semibold">Server and client</h2>

<p class="mt-3 max-w-[100ch] leading-7">
	The same scripts are compiled into both programs. Each script checks which side it runs on, with <code>Net::isClient(scene)</code>, and does only its own part:
</p>

<ul class="mt-3 max-w-[100ch] list-disc space-y-1.5 pl-6 leading-7">
	<li><strong>The server decides everything</strong>: it moves the rats from their players' keys, runs the physics, moves the obstacles, detects every hit, counts the laps and picks the winner.</li>
	<li><strong>The client shows it</strong>: it reads the keyboard and the mouse, sends them, and draws what the server sends, with the effects that do not change the game (shadow, dust, sounds, camera, HUD).</li>
</ul>

<p class="mt-3 max-w-[100ch] leading-7">
	Which side keeps an entity is set by its <code>Networked</code> component:
</p>

