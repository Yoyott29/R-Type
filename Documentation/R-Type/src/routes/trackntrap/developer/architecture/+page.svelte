<h2 class="mt-9 text-lg font-semibold">What crosses the network</h2>

<ul class="mt-3 max-w-[100ch] list-disc space-y-1.5 pl-6 leading-7">
	<li><strong>Server to clients</strong>, for every replicated entity: its <code>Transform</code>, plus two components of the game, <code>RatStatus</code> (one per rat) and <code>RaceStatus</code> (on the RaceInfo entity). See <a href="/trackntrap/developer/shared-state" class="text-accent hover:underline">Shared State</a>.</li>
	<li><strong>Client to server</strong>: the action bits of the player (forward, back, jump, trap, start) and the camera angle, packed into the same input.</li>
</ul>

<p class="mt-3 max-w-[100ch] leading-7">
	Nothing else is sent: a client works out the animation, the dust, the sounds and the HUD from these values.
</p>

