<h2 class="mt-9 text-lg font-semibold">Finding entities by their editor id</h2>

<p class="mt-3 max-w-[100ch] leading-7">
	A script often needs another entity: the HUD writes into texts, the rat plays sounds. Its parameters hold the <strong>editor id</strong> of that entity (the number shown next to it in the editor), and the <code>EditorEntityIds</code> resource turns it into the game entity:
</p>

<pre
	class="mt-3 overflow-x-auto rounded-md border border-[#1e2b26] bg-[#121a17] p-4 font-mono text-[13.5px] leading-6"><code>{code2}</code></pre>

<p class="mt-3 max-w-[100ch] leading-7">
	If you delete or recreate one of these entities in the editor, its id changes: update the parameters that point to it.
</p>

